// Imports the Kenney models the game uses (CC0: https://kenney.nl) from folders you have downloaded and unzipped, into apps/web/public/models/,
// and writes the catalog (lib/content/modelCatalog.js) with each model's real size read from the .glb file.
//
//   node scripts/models/import-kenney.mjs <folder with the unzipped kits>
//   where the folder contains  city-kit-commercial/  city-kit-suburban/  (each as unzipped from kenney.nl, with "Models/GLB format")
//
// Re-run it after changing the lists below. Nothing from the downloaded folders is executed: files are only copied and their headers read.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/models/import-kenney.mjs <folder with city-kit-commercial and city-kit-suburban>');
  process.exit(1);
}

// What to take from each kit, and what it is for (see lib/content/models.js for how a model is chosen).
const KITS = {
  commercial: {
    folder: 'city-kit-commercial',
    models: {
      tall: ['building-skyscraper-a', 'building-skyscraper-c', 'building-skyscraper-e', 'building-l', 'building-m'],
      mid: ['building-a', 'building-b', 'building-d', 'building-f', 'building-g', 'building-h', 'building-i'],
      low: ['building-c', 'building-e', 'building-k', 'building-j'],
      wide: ['building-n', 'building-j', 'building-k', 'building-e'],
    },
  },
  suburban: {
    folder: 'city-kit-suburban',
    models: { house: ['building-type-a', 'building-type-c', 'building-type-e', 'building-type-g', 'building-type-h', 'building-type-i', 'building-type-j', 'building-type-k', 'building-type-l', 'building-type-m', 'building-type-o', 'building-type-p', 'building-type-q', 'building-type-r'] },
  },
};

function readGlb(file) {
  const b = fs.readFileSync(file);
  if (b.readUInt32LE(0) !== 0x46546c67) throw new Error(`${file} is not a .glb`);
  const json = JSON.parse(b.subarray(20, 20 + b.readUInt32LE(12)).toString('utf8'));
  const min = [Infinity, Infinity, Infinity];
  const max = [-Infinity, -Infinity, -Infinity];
  let tris = 0;
  for (const m of json.meshes ?? []) {
    for (const p of m.primitives) {
      const a = json.accessors[p.attributes.POSITION];
      for (let i = 0; i < 3; i++) {
        min[i] = Math.min(min[i], a.min[i]);
        max[i] = Math.max(max[i], a.max[i]);
      }
      if (p.indices != null) tris += json.accessors[p.indices].count / 3;
    }
  }
  return { min, max, tris, bytes: b.length, images: (json.images ?? []).map((i) => i.uri) };
}

const catalog = [];
const seen = new Set();
for (const [kit, spec] of Object.entries(KITS)) {
  const from = path.join(source, spec.folder, 'Models', 'GLB format');
  if (!fs.existsSync(from)) throw new Error(`Missing ${from}`);
  const to = path.join(root, 'apps', 'web', 'public', 'models', 'kenney', kit);
  fs.mkdirSync(path.join(to, 'Textures'), { recursive: true });
  fs.copyFileSync(path.join(from, 'Textures', 'colormap.png'), path.join(to, 'Textures', 'colormap.png'));
  for (const [cls, names] of Object.entries(spec.models)) {
    for (const name of names) {
      const id = `${kit}/${name}`;
      const classes = catalog.find((c) => c.id === id);
      if (classes) {
        classes.classes.push(cls);
        continue;
      }
      const file = path.join(from, `${name}.glb`);
      const info = readGlb(file);
      if (info.images.some((u) => u !== 'Textures/colormap.png')) throw new Error(`${name} uses an unexpected texture`);
      fs.copyFileSync(file, path.join(to, `${name}.glb`));
      seen.add(id);
      catalog.push({
        id,
        kit,
        url: `/models/kenney/${kit}/${name}.glb`,
        classes: [cls],
        w: round(info.max[0] - info.min[0]),
        h: round(info.max[1] - info.min[1]),
        d: round(info.max[2] - info.min[2]),
        cx: round((info.max[0] + info.min[0]) / 2),
        cz: round((info.max[2] + info.min[2]) / 2),
        y0: round(info.min[1]),
        tris: info.tris,
        kb: Math.round(info.bytes / 1024),
      });
    }
  }
}
function round(n) {
  return Math.round(n * 1000) / 1000;
}

fs.writeFileSync(
  path.join(root, 'lib', 'content', 'modelCatalog.js'),
  `// GENERATED by scripts/models/import-kenney.mjs from the .glb files in apps/web/public/models/kenney: do not edit by hand.
// Sizes are in the model's own units (a building is about 1 unit wide); y0 is where the model's floor is; cx / cz are its centre.
// classes: tall | mid | low | wide (office and shop sizes) and house (the suburban kit).
export const MODEL_CATALOG = ${JSON.stringify(catalog, null, 1)};
export const MODEL_CREDIT = 'Buildings: Kenney City Kit (Commercial, Suburban), CC0, kenney.nl';
`
);
fs.writeFileSync(
  path.join(root, 'apps', 'web', 'public', 'models', 'CREDITS.md'),
  `# Model credits

The buildings in \`kenney/\` are from the **Kenney City Kit (Commercial)** and **City Kit (Suburban)**, made by Kenney (https://www.kenney.nl) and released under CC0 (public domain): https://creativecommons.org/publicdomain/zero/1.0/
Crediting Kenney is not required but is appreciated.

Voxel landmarks in \`vox/\` are made for this project (see scripts/models/make-sample-vox.mjs, or your own MagicaVoxel \`.vox\` files).
`
);
const kb = catalog.reduce((n, m) => n + m.kb, 0);
console.log(`${catalog.length} models, ${kb} KB, ${catalog.reduce((n, m) => n + m.tris, 0)} triangles in total`);
