// Packs data/street-names/*.json (made by road_generator.py) into lib/content/streetNames.js, which the generator and the /editor read.
//   node scripts/streets/build-names.mjs
// A city file ({ city, names }) becomes a name set (STREET_NAME_SETS, chosen with NEXT_PUBLIC_STREET_NAMES); districts.json
// ({ districts: { <district id>: { theme, source, names } } }) becomes DISTRICT_STREET_NAMES, the names of each district's own streets.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../../data/street-names/', import.meta.url));
const out = fileURLToPath(new URL('../../lib/content/streetNames.js', import.meta.url));
const sets = {};
let districts = {};
let attribution = '';
for (const f of readdirSync(dir).filter((n) => n.endsWith('.json')).sort()) {
  const j = JSON.parse(readFileSync(dir + f, 'utf8'));
  attribution = j.attribution || attribution;
  if (j.districts) districts = Object.fromEntries(Object.entries(j.districts).map(([id, d]) => [id, { theme: d.theme, source: d.source, names: d.names }]));
  else sets[f.replace(/\.json$/, '')] = { city: j.city, names: j.names };
}
const text = `// Generated by scripts/streets/build-names.mjs from data/street-names/*.json. Do not edit by hand.
export const STREET_NAME_ATTRIBUTION = ${JSON.stringify(attribution || 'Street names (c) OpenStreetMap contributors, ODbL 1.0')};
export const STREET_NAME_SETS = ${JSON.stringify(sets, null, 1)};
export const DISTRICT_STREET_NAMES = ${JSON.stringify(districts, null, 1)};
`;
writeFileSync(out, text);
console.log(`${Object.keys(sets).length} name sets and ${Object.keys(districts).length} district lists -> lib/content/streetNames.js`);
