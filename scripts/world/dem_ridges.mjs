// Real heights for Jamaica's mountains (docs/world/world_recipe.md 4c). Downloads the public AWS "terrarium" elevation tiles (Mapzen terrain tiles: SRTM and other open sources) for the island,
// decodes them to metres, and writes the ridge lines and peaks of each range to lib/world/data/jamaicaDem.js, which shapes.js reads. Run it again only to change the ranges below.
//   node scripts/world/dem_ridges.mjs [cache-dir]       (tiles are cached in the directory, default a temp folder; the output is small and committed)
// Attribution: see CREDITS.md ("Elevation").
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';

const Z = 10; // about 145 m a pixel at this latitude
const cache = process.argv[2] ?? path.join(os.tmpdir(), 'jamaica-dem');
fs.mkdirSync(cache, { recursive: true });
const out = new URL('../../lib/world/data/jamaicaDem.js', import.meta.url);

const n = 2 ** Z;
const tileX = (lon) => ((lon + 180) / 360) * n;
const tileY = (lat) => ((1 - Math.asinh(Math.tan((lat * Math.PI) / 180)) / Math.PI) / 2) * n;
const tiles = new Map();
async function tile(x, y) {
  const key = `${x}_${y}`;
  if (tiles.has(key)) return tiles.get(key);
  const file = path.join(cache, `${key}.png`);
  if (!fs.existsSync(file)) {
    const res = await fetch(`https://s3.amazonaws.com/elevation-tiles-prod/terrarium/${Z}/${x}/${y}.png`);
    if (!res.ok) throw new Error(`tile ${key}: ${res.status}`);
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  const { data, info } = await sharp(file).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const t = { data, w: info.width };
  tiles.set(key, t);
  return t;
}
/** Height in metres at a longitude and latitude. */
async function metres(lon, lat) {
  const fx = tileX(lon), fy = tileY(lat);
  const t = await tile(Math.floor(fx), Math.floor(fy));
  const px = Math.min(255, Math.floor((fx % 1) * 256)), py = Math.min(255, Math.floor((fy % 1) * 256));
  const i = (py * t.w + px) * 3;
  return t.data[i] * 256 + t.data[i + 1] + t.data[i + 2] / 256 - 32768;
}

// Each range is a search box (the real range lies inside it) and the direction it runs. The ridge is found by cutting the box into slices across that direction and taking the highest ground
// in each slice (smoothed), so it follows the real crest.
const RANGES = [
  { name: 'Blue Mountains', box: [-76.80, 17.98, -76.43, 18.16], along: 'lon', slices: 14 },
  { name: 'John Crow Mountains', box: [-76.42, 18.00, -76.30, 18.18], along: 'lat', slices: 6 },
  { name: 'Cockpit Country', box: [-77.85, 18.20, -77.50, 18.38], along: 'lon', slices: 6 },
  { name: 'Dolphin Head', box: [-78.25, 18.30, -78.10, 18.42], along: 'lat', slices: 4 },
  { name: 'The Central Hills', box: [-77.50, 18.08, -77.20, 18.28], along: 'lon', slices: 6 },
];
const STEP = 0.004; // degrees, a little under 450 m
const result = { source: 'AWS Terrain Tiles (terrarium, zoom 10): SRTM and other open elevation data', generated: new Date().toISOString().slice(0, 10), ranges: [] };
for (const r of RANGES) {
  const [x0, y0, x1, y1] = r.box;
  const grid = [];
  for (let lat = y0; lat <= y1; lat += STEP) for (let lon = x0; lon <= x1; lon += STEP) grid.push({ lon, lat, h: await metres(lon, lat) });
  const lo = r.along === 'lon' ? x0 : y0, hi = r.along === 'lon' ? x1 : y1;
  const line = [];
  for (let i = 0; i < r.slices; i++) {
    const a = lo + ((hi - lo) * i) / r.slices, b = lo + ((hi - lo) * (i + 1)) / r.slices;
    const cell = grid.filter((p) => { const v = r.along === 'lon' ? p.lon : p.lat; return v >= a && v < b; });
    const top = cell.reduce((m, p) => (p.h > m.h ? p : m), cell[0]);
    // the crest of the slice: the mean of the points within 15 per cent of its top, so it is the ridge's middle and not one spike
    const crest = cell.filter((p) => p.h >= top.h * 0.85);
    line.push({ lon: crest.reduce((s, p) => s + p.lon, 0) / crest.length, lat: crest.reduce((s, p) => s + p.lat, 0) / crest.length, m: Math.round(top.h) });
  }
  const peak = grid.reduce((m, p) => (p.h > m.h ? p : m), grid[0]);
  result.ranges.push({ name: r.name, peakMetres: Math.round(peak.h), peak: { lon: +peak.lon.toFixed(4), lat: +peak.lat.toFixed(4) }, ridge: line.map((p) => ({ lon: +p.lon.toFixed(4), lat: +p.lat.toFixed(4), m: p.m })) });
  console.log(r.name, 'peak', Math.round(peak.h), 'm at', peak.lat.toFixed(3), peak.lon.toFixed(3), '| ridge', line.map((p) => `${p.lat.toFixed(2)},${p.lon.toFixed(2)}:${p.m}`).join(' '));
}
fs.mkdirSync(path.dirname(new URL(out).pathname.replace(/^\/([A-Za-z]:)/, '$1')), { recursive: true });
fs.writeFileSync(out, `// Generated by scripts/world/dem_ridges.mjs from real elevation data (see CREDITS.md, "Elevation"). Do not edit by hand.\nexport const JAMAICA_DEM = ${JSON.stringify(result, null, 1)};\n`);
console.log('written', out.pathname);
